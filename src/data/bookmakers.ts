function accaBoost(headline: string, details: string): Offer {
  return { headline, type: "acca-bonus", details };
}

/* ---------- helpers ---------- */

export const RATING_WEIGHTS: Record<keyof Bookmaker["ratings"], number> = {
  odds: 0.25,
  markets: 0.2,
  bonuses: 0.15,
  app: 0.15,
  payments: 0.15,
  support: 0.1,
};

export function overallRating(b: Bookmaker): number {
  const total = (Object.keys(RATING_WEIGHTS) as (keyof Bookmaker["ratings"])[]).reduce((s, k) => s + b.ratings[k] * RATING_WEIGHTS[k], 0);
  return Math.round(total * 10) / 10;
}

export const bookmakerBySlug = (slug: string) => bookmakers.find((b) => b.slug === slug);

export function bookmakersInCountry(code: CountryCode): Bookmaker[] {
  return bookmakers.filter((b) => b.markets.some((m) => m.country === code)).sort((a, b) => overallRating(b) - overallRating(a));
}

export function marketFor(b: Bookmaker, code: CountryCode) {
  return b.markets.find((m) => m.country === code);
}

export function primaryMarket(b: Bookmaker) {
  return b.markets[0];
}

export function bookingCodeBookmakers(): Bookmaker[] {
  return bookmakers.filter((b) => b.features.bookingCode && b.bookingCode);
}
